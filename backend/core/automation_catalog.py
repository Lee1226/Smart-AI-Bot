class AutomationCatalogError(Exception):
    """An expected catalog validation or storage error."""

    def __init__(self, status_code: int, detail: str):
        super().__init__(detail)
        self.status_code = status_code
        self.detail = detail


def validate_resource_id(value: str, label: str = "资源 ID") -> str:
    """Validate an ID before it is used in a catalog path."""
    if not isinstance(value, str) or not RESOURCE_ID.fullmatch(value) or value in {".", ".."}:
        raise AutomationCatalogError(
            400, f"{label} 必须是 1-128 位字母、数字、点、下划线或短横线"
        )
    return value


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _as_non_empty_string(value: Any, field: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise AutomationCatalogError(400, f"manifest 缺少有效的 {field}")
    return value.strip()


def _safe_relative_path(value: str, label: str) -> str:
    """Normalize a relative POSIX path without accepting traversal."""
    if (
        not isinstance(value, str)
        or not value
        or value.startswith("/")
        or "\\" in value
        or PureWindowsPath(value).is_absolute()
        or any(ord(character) < 32 or ord(character) == 127 for character in value)
    ):
        raise AutomationCatalogError(400, f"{label} 文件名无效")
    path = PurePosixPath(value)
    if path.is_absolute() or ".." in path.parts or not path.parts or path.as_posix() == ".":
        raise AutomationCatalogError(400, f"{label} 文件名无效")
    return path.as_posix()


def _sab_screenshot_path(value: str, label: str = "截图") -> str:
    """Normalize every Case screenshot to SAB's ``flow.assets`` layout."""
    safe_path = _safe_relative_path(value, label)
    return f"flow.assets/{PurePosixPath(safe_path).name}"


def _normalize_dependencies(value: Any, label: str) -> list[dict[str, Any]]:
    if not isinstance(value, list):
        raise AutomationCatalogError(400, f"{label} 必须是对象列表")
    normalized: list[dict[str, Any]] = []
    for dependency in value:
        if not isinstance(dependency, dict):
            raise AutomationCatalogError(400, f"{label} 必须是对象列表")
        case_id = validate_resource_id(
            _as_non_empty_string(dependency.get("caseID"), f"{label}.caseID"),
            "Case ID",
        )
        version = dependency.get("version")
        if isinstance(version, bool) or not isinstance(version, int) or version < 1:
            raise AutomationCatalogError(400, f"{label}.version 必须是正整数")
        sha256 = dependency.get("sha256")
        if not isinstance(sha256, str) or not SHA256.fullmatch(sha256):
            raise AutomationCatalogError(400, f"{label}.sha256 必须是 64 位 SHA-256")
        normalized.append({"caseID": case_id, "version": version, "sha256": sha256.lower()})
    return normalized


def _safe_archive_names(archive: zipfile.ZipFile) -> set[str]:
    names: set[str] = set()
    uncompressed_bytes = 0
    for info in archive.infolist():
        if len(names) >= MAX_ARCHIVE_ENTRIES:
            raise AutomationCatalogError(400, "ZIP 包条目数量超过限制")
        name = info.filename
        if name in names:
            raise AutomationCatalogError(400, f"ZIP 包包含重复文件：{name}")
        if any(ord(character) < 32 or ord(character) == 127 for character in name):
            raise AutomationCatalogError(400, "ZIP 包包含不安全路径")
        _safe_relative_path(name, "ZIP 条目")
        parts = PurePosixPath(name).parts
        if ".." in parts:
            raise AutomationCatalogError(400, "ZIP 包包含路径穿越条目")
        uncompressed_bytes += max(info.file_size, 0)
        if uncompressed_bytes > MAX_ARCHIVE_UNCOMPRESSED_BYTES:
            raise AutomationCatalogError(413, "ZIP 包解压总大小超过限制")
        names.add(name)
    return names


def _read_package(
    source: Path,
    required: tuple[str, ...],
    kind: CatalogKind,
) -> tuple[dict[str, Any], bytes]:
    try:
        with zipfile.ZipFile(source) as archive:
            names = _safe_archive_names(archive)
            missing = [name for name in required if name not in names]
            if missing:
                label = "Case" if kind == "cases" else "Plan"
                raise AutomationCatalogError(
                    400, f"{label} 包缺少：{', '.join(missing)}"
                )
            if archive.testzip() is not None:
                raise AutomationCatalogError(400, "ZIP 包校验失败")
            try:
                package_manifest = json.loads(archive.read("manifest.json").decode("utf-8"))
            except (UnicodeDecodeError, json.JSONDecodeError) as error:
                raise AutomationCatalogError(400, "ZIP 包的 manifest.json 无效") from error
            if not isinstance(package_manifest, dict):
                raise AutomationCatalogError(400, "ZIP 包的 manifest.json 必须是对象")
            payload_name = "flow.yaml" if kind == "cases" else "plan.yaml"
            try:
                payload = archive.read(payload_name)
                payload.decode("utf-8")
            except (KeyError, UnicodeDecodeError) as error:
                raise AutomationCatalogError(400, f"ZIP 包缺少有效的 {payload_name}") from error
            return package_manifest, payload
    except zipfile.BadZipFile as error:
        raise AutomationCatalogError(400, "上传文件不是有效的 ZIP 包") from error
    except (RuntimeError, NotImplementedError, zlib.error) as error:
        raise AutomationCatalogError(400, "ZIP 无效或无法读取") from error
    except OSError as error:
        raise AutomationCatalogError(400, "无法读取上传的 ZIP 包") from error


def _format_wait(milliseconds: int) -> str:
    if milliseconds % 1000 == 0:
        seconds = milliseconds // 1000
        if seconds >= 60 and seconds % 60 == 0:
            return f"等待 {seconds // 60} 分钟"
        return f"等待 {seconds} 秒"
    return f"等待 {milliseconds / 1000:g} 秒"


_STEP_MARKER = re.compile(
    r"^[ \t]*# sab-(?P<kind>recorded-step|fixed-wait-ms|(?:visual-)?popup-guard)"
    r"(?::[ \t]*(?P<payload>.*))?[ \t]*$",
    re.MULTILINE,
)
_ACTION = re.compile(
    r"^[ \t]*-[ \t]*(?P<name>"
    r"tapOn|doubleTapOn|longPressOn|swipe|scroll|scrollUntilVisible|"
    r"inputText|eraseText|pressKey|hideKeyboard|assertVisible|assertNotVisible|"
    r"assertTrue|assertFalse|runFlow|waitForAnimationToEnd|launchApp|stopApp|"
    r"clearState|clearKeychain|back|openLink|addMedia|takeScreenshot|"
    r"copyTextFrom|evalScript|repeat)"
    r"(?::[ \t]*(?P<inline>[^\n]*)|[ \t]*)$",
    re.MULTILINE,
)
_DETAIL = re.compile(
    r"^[ \t]+(?P<key>id|text|point|timeout|file):[ \t]*(?P<value>[^\n]+)",
    re.MULTILINE,
)


def parse_case_steps(flow: str) -> list[dict[str, Any]]:
    """Turn SAB recorder comments into data suitable for a detail view."""
    markers = list(_STEP_MARKER.finditer(flow))
    steps: list[dict[str, Any]] = []
    for index, marker in enumerate(markers, 1):
        end = markers[index].start() if index < len(markers) else len(flow)
        block = flow[marker.start():end]
        marker_kind = marker.group("kind")
        payload = (marker.group("payload") or "").strip()
        if marker_kind.endswith("popup-guard"):
            try:
                guard = json.loads(payload)
                title = str(guard.get("title") or "守卫弹窗") if isinstance(guard, dict) else "守卫弹窗"
            except (TypeError, json.JSONDecodeError):
                guard = {}
                title = "守卫弹窗"
            steps.append({
                "index": index,
                "kind": "guard",
                "action": title,
                "popup_guard": {
                    "title": title,
                    "mode": "视觉匹配" if marker_kind.startswith("visual-") else "控件匹配",
                },
            })
            continue
        if marker_kind == "fixed-wait-ms":
            try:
                milliseconds = int(payload)
            except ValueError:
                milliseconds = 0
            if milliseconds < 0:
                milliseconds = 0
            steps.append({
                "index": index,
                "kind": "wait",
                "action": _format_wait(milliseconds),
                "wait_ms": milliseconds,
            })
            continue

        before = re.search(r"^#[ \t]*sab-before-screenshot:[ \t]*([^\s]+)", block, re.MULTILINE)
        result = re.search(r"^#[ \t]*sab-result-screenshot:[ \t]*([^\s]+)", block, re.MULTILINE)
        action_match = _ACTION.search(block)
        action_name = action_match.group("name") if action_match else ""
        target = (action_match.group("inline") or "").strip() if action_match else ""
        if action_match:
            detail = _DETAIL.search(block, action_match.end())
            if detail:
                target = f"{detail.group('key')}: {detail.group('value').strip().strip(chr(34))}"
        labels = {
            "tapOn": "点击",
            "doubleTapOn": "双击",
            "longPressOn": "长按",
            "swipe": "滑动",
            "scroll": "滚动",
            "scrollUntilVisible": "滚动查找",
            "inputText": "输入文本",
            "eraseText": "清除文本",
            "pressKey": "按键",
            "hideKeyboard": "隐藏键盘",
            "assertVisible": "校验可见",
            "assertNotVisible": "校验不可见",
            "assertTrue": "校验为真",
            "assertFalse": "校验为假",
            "waitForAnimationToEnd": "等待动画",
            "runFlow": "执行子流程",
            "launchApp": "启动应用",
            "stopApp": "停止应用",
            "clearState": "清理应用状态",
            "clearKeychain": "清理密钥链",
            "back": "返回",
            "openLink": "打开链接",
            "addMedia": "添加媒体",
            "takeScreenshot": "截图",
            "copyTextFrom": "复制文本",
            "evalScript": "执行脚本",
            "repeat": "重复执行",
        }
        action = labels.get(action_name, "录制步骤")
        if target:
            action = f"{action} {target}"
        step: dict[str, Any] = {
            "index": index,
            "kind": "action",
            "action": action,
            "recorded_step": payload,
            "before_screenshot": _sab_screenshot_path(before.group(1), "截图引用") if before else "",
            "screenshot": _sab_screenshot_path(result.group(1), "截图引用") if result else "",
        }
        if action_name:
            step["action_name"] = action_name
        steps.append(step)
    return steps


def case_screenshot_references(flow: str) -> set[str]:
    """Return SAB's canonical ``flow.assets`` screenshot references."""
    return {
        _sab_screenshot_path(match.group(1).rstrip(" \t"), "截图引用")
        for match in re.finditer(
            r"^#[ \t]*sab-(?:before|result)-screenshot:[ \t]*([^\n]*)$",
            flow,
            re.MULTILINE,
        )
    }


def _validate_case_screenshot_references(
    references: set[str], screenshot_names: Sequence[str]
) -> None:
    """Require Case comments and stored screenshots to use one SAB rule."""
    uploaded = set(screenshot_names)
    missing = sorted(references - uploaded)
    if missing:
        raise AutomationCatalogError(400, f"Case 引用了未上传的截图：{', '.join(missing)}")


def _case_content_sha256(
    manifest: dict[str, Any], flow: bytes, screenshots: Sequence[tuple[str, str]]
) -> str:
    canonical_manifest = {
        key: value for key, value in manifest.items() if key not in {"changeNote", "validation"}
    }
    payload = {
        "manifest": canonical_manifest,
        "flow_sha256": hashlib.sha256(flow).hexdigest(),
        "screenshots": [
            {"name": name, "sha256": digest}
            for name, digest in sorted(screenshots)
        ],
    }
    canonical = json.dumps(payload, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def _plan_content_sha256(
    manifest: dict[str, Any],
    package_manifest: dict[str, Any],
    plan: bytes,
    dependencies: Sequence[dict[str, Any]],
) -> str:
    def canonical_manifest(source: dict[str, Any]) -> dict[str, Any]:
        value = {
            key: item for key, item in source.items() if key not in {"changeNote", "validation"}
        }
        # Dependencies are represented by their normalized form so digest casing
        # does not create a distinct content version.
        value["dependencies"] = list(dependencies)
        return value

    payload = {
        "manifest": canonical_manifest(manifest),
        "package_manifest": canonical_manifest(package_manifest),
        "plan_sha256": hashlib.sha256(plan).hexdigest(),
        "dependencies": list(dependencies),
    }
    canonical = json.dumps(payload, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


class AutomationCatalog:
    """Filesystem catalog with atomic index writes and versioned packages."""

    def __init__(self, root: Path | str = DEFAULT_ROOT):
        self.root = Path(root).resolve()
        self.index_path = self.root / "index.json"
        self.lock_path = self.root / ".index.lock"
        self._thread_lock = threading.RLock()
        self._cleanup_expired_downloads()

    def _cleanup_expired_downloads(self) -> None:
        download_root = self.root / ".downloads"
        if not download_root.is_dir():
            return
        cutoff = time.time() - DOWNLOAD_TTL_SECONDS
        for path in download_root.glob("download-*"):
            try:
                if path.is_file() and path.stat().st_mtime < cutoff:
                    path.unlink()
            except OSError:
                logger.warning("下载临时文件清理失败：%s", path, exc_info=True)

    @contextmanager
    def _locked(self) -> Iterator[None]:
        self.root.mkdir(parents=True, exist_ok=True)
        with self._thread_lock:
            with self.lock_path.open("a+b") as lock_file:
                if fcntl is not None:
                    fcntl.flock(lock_file.fileno(), fcntl.LOCK_EX)
                try:
                    yield
                finally:
                    if fcntl is not None:
                        fcntl.flock(lock_file.fileno(), fcntl.LOCK_UN)

    def _load_index(self) -> dict[str, Any]:
        if not self.index_path.exists():
            return {"cases": {}, "plans": {}}
        try:
            value = json.loads(self.index_path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
            raise AutomationCatalogError(500, "自动化资源索引损坏") from error
        if not isinstance(value, dict) or not all(isinstance(value.get(kind), dict) for kind in ("cases", "plans")):
            raise AutomationCatalogError(500, "自动化资源索引损坏")
        return value

    def _save_index(self, value: dict[str, Any]) -> None:
        fd, temporary = tempfile.mkstemp(prefix="index-", suffix=".json", dir=self.root)
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as output:
                json.dump(value, output, ensure_ascii=False, indent=2)
                output.write("\n")
                output.flush()
                os.fsync(output.fileno())
            os.replace(temporary, self.index_path)
            try:
                directory_fd = os.open(self.root, os.O_DIRECTORY)
                try:
                    os.fsync(directory_fd)
                finally:
                    os.close(directory_fd)
            except (AttributeError, OSError):
                pass
        finally:
            Path(temporary).unlink(missing_ok=True)

    def _scoped_record(self, record: dict[str, Any], account_id: str | None) -> bool:
        return record.get("account_id") == account_id

    @staticmethod
    def _record_key(resource_id: str, account_id: str | None) -> str:
        if account_id:
            namespace = hashlib.sha256(account_id.encode("utf-8")).hexdigest()[:32]
            return f"{namespace}:{resource_id}"
        return resource_id

    def _find_record(
        self, index: dict[str, Any], kind: CatalogKind, resource_id: str, account_id: str | None
    ) -> tuple[str, dict[str, Any]] | None:
        key = self._record_key(resource_id, account_id)
        record = index[kind].get(key)
        if isinstance(record, dict) and self._scoped_record(record, account_id):
            return key, record
        # Keep compatibility with a local index written before account-aware
        # keys were introduced.
        for candidate_key, candidate in index[kind].items():
            if (
                isinstance(candidate, dict)
                and candidate.get("id") == resource_id
                and self._scoped_record(candidate, account_id)
            ):
                return candidate_key, candidate
        return None

    def _record_path(self, version: dict[str, Any]) -> Path:
        relative = version.get("file_name")
        if not isinstance(relative, str) or not relative:
            raise AutomationCatalogError(500, "自动化资源文件索引无效")
        path = (self.root / relative).resolve()
        try:
            path.relative_to(self.root)
        except ValueError as error:
            raise AutomationCatalogError(500, "自动化资源文件索引包含不安全路径") from error
        return path

    def _storage_root(self, kind: CatalogKind, resource_id: str, account_id: str | None) -> Path:
        # Local deployments keep the workspace layout. Authenticated tenants
        # get a namespace so equal IDs cannot overwrite another account's files.
        if account_id:
            namespace = hashlib.sha256(account_id.encode("utf-8")).hexdigest()[:32]
            return self.root / "accounts" / namespace / kind / resource_id
        return self.root / kind / resource_id

    @staticmethod
    def _public(value: Any) -> Any:
        if isinstance(value, dict):
            return {
                key: AutomationCatalog._public(item)
                for key, item in value.items()
                if key not in {"file_name", "account_id"}
            }
        if isinstance(value, list):
            return [AutomationCatalog._public(item) for item in value]
        return value

    def _public_version(
        self, version: dict[str, Any], kind: CatalogKind, include_detail: bool
    ) -> dict[str, Any]:
        value = self._public(version)
        source = self._record_path(version)
        if not source.is_file():
            raise AutomationCatalogError(404, "自动化资源文件不存在")
        if kind == "cases" and include_detail:
            try:
                _, flow = _read_package(source, ("manifest.json", "flow.yaml"), kind)
                value["flow_yaml"] = flow.decode("utf-8")
                value["steps"] = parse_case_steps(value["flow_yaml"])
            except AutomationCatalogError as error:
                raise AutomationCatalogError(500, f"自动化 Case 包损坏：{error.detail}") from error
        elif kind == "plans" and include_detail:
            try:
                _, plan = _read_package(source, ("manifest.json", "plan.yaml"), kind)
                value["plan_yaml"] = plan.decode("utf-8")
            except AutomationCatalogError as error:
                raise AutomationCatalogError(500, f"自动化 Plan 包损坏：{error.detail}") from error
        return value

    async def _write_upload(
        self, upload: UploadFile, target: Path, max_bytes: int, label: str
    ) -> str:
        target.parent.mkdir(parents=True, exist_ok=True)
        temporary = target.with_name(f".{target.name}.{uuid.uuid4().hex}.uploading")
        digest = hashlib.sha256()
        try:
            total = 0
            with temporary.open("wb") as output:
                while chunk := await upload.read(1024 * 1024):
                    total += len(chunk)
                    if total > max_bytes:
                        raise AutomationCatalogError(413, f"{label}大小超过限制")
                    digest.update(chunk)
                    output.write(chunk)
                output.flush()
                os.fsync(output.fileno())
            os.replace(temporary, target)
        finally:
            await upload.close()
            temporary.unlink(missing_ok=True)
        return digest.hexdigest()

    @staticmethod
    def _clean_temp(path: Path) -> None:
        shutil.rmtree(path, ignore_errors=True)

    @staticmethod
    def _rollback_paths(paths: Sequence[Path]) -> None:
        for path in reversed(paths):
            try:
                if path.is_dir():
                    shutil.rmtree(path)
                else:
                    path.unlink(missing_ok=True)
            except OSError:
                logger.warning("自动化资源回滚失败，保留孤儿文件：%s", path, exc_info=True)

    def _download_snapshot(self, source: Path) -> tuple[Path, str]:
        self._cleanup_expired_downloads()
        download_root = self.root / ".downloads"
        download_root.mkdir(parents=True, exist_ok=True)
        fd, temporary = tempfile.mkstemp(prefix="download-", dir=download_root)
        try:
            with source.open("rb") as input_file, os.fdopen(fd, "wb") as output:
                fd = -1
                shutil.copyfileobj(input_file, output, length=1024 * 1024)
                output.flush()
                os.fsync(output.fileno())
            os.utime(temporary, None)
            return Path(temporary), source.name
        except Exception:
            if fd != -1:
                os.close(fd)
            Path(temporary).unlink(missing_ok=True)
            raise

    def list_resources(self, kind: CatalogKind, query: str, account_id: str | None) -> list[dict[str, Any]]:
        needle = query.strip().lower()
        with self._locked():
            index = self._load_index()
            items: list[dict[str, Any]] = []
            for record in index[kind].values():
                if not self._scoped_record(record, account_id) or not record.get("versions"):
                    continue
                version = max(record["versions"], key=lambda item: int(item.get("version", 0)))
                item = {
                    **self._public(record),
                    **self._public_version(version, kind, include_detail=False),
                    "latest_version": version["version"],
                }
                haystack = " ".join(
                    [str(item.get("id", "")), str(item.get("name", "")), str(item.get("description", ""))]
                    + [str(tag) for tag in item.get("tags", [])]
                ).lower()
                if not needle or needle in haystack:
                    items.append(item)
            return sorted(items, key=lambda item: item.get("updated_at", ""), reverse=True)

    def get_resource(self, kind: CatalogKind, resource_id: str, account_id: str | None) -> dict[str, Any]:
        validate_resource_id(resource_id)
        with self._locked():
            found = self._find_record(self._load_index(), kind, resource_id, account_id)
            if not found:
                raise AutomationCatalogError(404, "资源不存在")
            _, record = found
            result = {**self._public(record)}
            result["versions"] = [
                self._public_version(version, kind, include_detail=True)
                for version in record.get("versions", [])
            ]
            return result

    def delete_resource(self, kind: CatalogKind, resource_id: str, account_id: str | None) -> None:
        validate_resource_id(resource_id)
        with self._locked():
            index = self._load_index()
            found = self._find_record(index, kind, resource_id, account_id)
            if not found:
                raise AutomationCatalogError(404, "资源不存在")
            record_key, record = found
            index[kind].pop(record_key)
            resource_root = self._storage_root(kind, resource_id, account_id)
            self._save_index(index)
            try:
                shutil.rmtree(resource_root)
            except FileNotFoundError:
                pass
            except OSError:
                logger.warning("自动化资源删除后清理失败，保留孤儿文件：%s", resource_root, exc_info=True)

    def _finalize_case(
        self,
        manifest: dict[str, Any],
        case_id: str,
        name: str,
        temp_package: Path,
        screenshot_root: Path,
        screenshot_names: list[str],
        screenshot_digests: list[str],
        package_sha256: str,
        account_id: str | None,
        uploaded_by: str = "local",
    ) -> dict[str, Any]:
        package_manifest, flow = _read_package(temp_package, ("manifest.json", "flow.yaml"), "cases")
        if package_manifest.get("caseID") != case_id or package_manifest.get("name") != name:
            raise AutomationCatalogError(400, "ZIP 包 manifest 与上传 manifest 的 Case 信息不一致")
        _validate_case_screenshot_references(
            case_screenshot_references(flow.decode("utf-8")), screenshot_names
        )
        content_sha256 = _case_content_sha256(
            manifest, flow, list(zip(screenshot_names, screenshot_digests))
        )
        with self._locked():
            index = self._load_index()
            found = self._find_record(index, "cases", case_id, account_id)
            record = found[1] if found else None
            if record is None:
                record = {
                    "id": case_id, "name": name, "description": "", "tags": [],
                    "target_package": "", "account_id": account_id, "versions": [],
                }
                index["cases"][self._record_key(case_id, account_id)] = record
            duplicate = next(
                (version for version in record["versions"] if version.get("content_sha256") == content_sha256),
                None,
            )
            if duplicate:
                raise AutomationCatalogError(409, f"内容未变化，已存在 Case v{duplicate['version']}，无需重复上传")
            version_number = max(
                (int(version.get("version", 0)) for version in record["versions"]), default=0
            ) + 1
            resource_root = self._storage_root("cases", case_id, account_id)
            package_path = resource_root / f"v{version_number}.sabcase"
            package_path.parent.mkdir(parents=True, exist_ok=True)
            final_screenshots = resource_root / f"v{version_number}" / "screenshots"
            moved_paths: list[Path] = []
            try:
                os.replace(temp_package, package_path)
                moved_paths.append(package_path)
                if screenshot_root.exists():
                    final_screenshots.parent.mkdir(parents=True, exist_ok=True)
                    os.replace(screenshot_root, final_screenshots)
                    moved_paths.append(final_screenshots)
                version_record = {
                    "version": version_number, "sha256": package_sha256,
                    "content_sha256": content_sha256,
                    "file_name": str(package_path.relative_to(self.root)),
                    "created_at": _now(), "updated_at": _now(), "uploaded_by": uploaded_by,
                    "change_note": str(manifest.get("changeNote", "")),
                    "validation": manifest.get("validation", {"status": "passed"}),
                    "screenshots": screenshot_names,
                    "steps": parse_case_steps(flow.decode("utf-8")),
                }
                record.update({
                    "name": name, "description": str(manifest.get("description", "")),
                    "tags": list(manifest.get("tags", [])) if isinstance(manifest.get("tags", []), list) else [],
                    "target_package": str(manifest.get("targetPackage", "")),
                    "updated_at": version_record["updated_at"],
                })
                record["versions"].append(version_record)
                self._save_index(index)
                return {"item": self._public(record), "version": version_number, "sha256": package_sha256}
            except Exception:
                self._rollback_paths(moved_paths)
                raise

    async def publish_case(
        self,
        manifest_text: str,
        package: UploadFile,
        screenshots: Sequence[UploadFile],
        account_id: str | None,
        uploaded_by: str = "local",
    ) -> dict[str, Any]:
        if len(manifest_text.encode("utf-8")) > MAX_MANIFEST_BYTES:
            raise AutomationCatalogError(413, "Case manifest 大小超过限制")
        try:
            manifest = json.loads(manifest_text)
        except (TypeError, json.JSONDecodeError) as error:
            raise AutomationCatalogError(400, "Case manifest 不是有效 JSON") from error
        if not isinstance(manifest, dict):
            raise AutomationCatalogError(400, "Case manifest 必须是对象")
        case_id = validate_resource_id(_as_non_empty_string(manifest.get("caseID"), "caseID"), "Case ID")
        name = _as_non_empty_string(manifest.get("name"), "name")
        if not (package.filename or "").lower().endswith(".sabcase"):
            raise AutomationCatalogError(400, "Case 包必须使用 .sabcase 扩展名")

        temp_root = self._storage_root("cases", case_id, account_id) / ".incoming" / uuid.uuid4().hex
        temp_package = temp_root / "package.sabcase"
        screenshot_root = temp_root / "screenshots"
        try:
            if len(screenshots) > MAX_SCREENSHOTS:
                raise AutomationCatalogError(400, "Case 截图数量超过限制")
            package_sha256 = await self._write_upload(
                package, temp_package, MAX_CASE_PACKAGE_BYTES, "Case 包"
            )
            screenshot_names: list[str] = []
            screenshot_digests: list[str] = []
            screenshot_total = 0
            for index, screenshot in enumerate(screenshots, 1):
                original = _sab_screenshot_path(
                    screenshot.filename or f"screenshot-{index:02d}.png", "截图"
                )
                if original in screenshot_names:
                    raise AutomationCatalogError(400, f"Case 包含重复截图文件名：{original}")
                screenshot_digest = await self._write_upload(
                    screenshot,
                    screenshot_root / original,
                    MAX_SCREENSHOT_BYTES,
                    "截图",
                )
                screenshot_total += (screenshot_root / original).stat().st_size
                if screenshot_total > MAX_CASE_SCREENSHOTS_BYTES:
                    raise AutomationCatalogError(413, "Case 截图总大小超过限制")
                screenshot_names.append(original)
                screenshot_digests.append(screenshot_digest)
            return await asyncio.to_thread(
                self._finalize_case,
                manifest,
                case_id,
                name,
                temp_package,
                screenshot_root,
                screenshot_names,
                screenshot_digests,
                package_sha256,
                account_id,
                uploaded_by,
            )
        finally:
            self._clean_temp(temp_root)

    async def publish_case_workspace(
        self,
        case_id: str,
        name: str,
        description: str,
        tags: Sequence[str],
        flow_path: str,
        files: Sequence[UploadFile],
        account_id: str | None,
        uploaded_by: str = "local",
    ) -> dict[str, Any]:
        """Build and publish a Case directly from the Maestro workspace layout.

        Maestro keeps a flow beside an optional ``<flow>.assets`` directory. The
        desktop client turns those files into a ``.sabcase`` archive before
        sending it to the workspace; Smart-Bot now performs the same packaging locally.
        """
        case_id = validate_resource_id(case_id.strip(), "Case ID")
        name = _as_non_empty_string(name, "name")
        flow_path = _safe_relative_path(flow_path, "flow")
        normalized_tags = [str(tag).strip() for tag in tags if str(tag).strip()]
        if len(files) == 0:
            raise AutomationCatalogError(400, "请选择 Maestro Case 目录")
        # The generated manifest and, for a nested selected flow, canonical
        # ``flow.yaml`` also occupy archive entries.
        if len(files) > MAX_ARCHIVE_ENTRIES - 2:
            raise AutomationCatalogError(400, "Case 文件数量超过限制")

        temp_root = self._storage_root("cases", case_id, account_id) / ".incoming" / uuid.uuid4().hex
        workspace_root = temp_root / "workspace"
        temp_package = temp_root / "package.sabcase"
        screenshot_root = temp_root / "screenshots"
        try:
            total_bytes = 0
            stored: set[str] = set()
            for index, upload in enumerate(files, 1):
                relative = _safe_relative_path(
                    upload.filename or f"file-{index:03d}", "Case 文件"
                )
                if relative in stored:
                    raise AutomationCatalogError(400, f"Case 包含重复文件：{relative}")
                stored.add(relative)
                target = workspace_root / relative
                digest_size_before = target.stat().st_size if target.exists() else 0
                await self._write_upload(upload, target, MAX_CASE_PACKAGE_BYTES, "Case 文件")
                total_bytes += max(target.stat().st_size - digest_size_before, 0)
                if total_bytes > MAX_ARCHIVE_UNCOMPRESSED_BYTES:
                    raise AutomationCatalogError(413, "Case 文件总大小超过限制")

            flow_file = workspace_root / flow_path
            if not flow_file.is_file():
                raise AutomationCatalogError(400, f"找不到 Case flow：{flow_path}")
            try:
                flow = flow_file.read_bytes()
                flow.decode("utf-8")
            except (OSError, UnicodeDecodeError) as error:
                raise AutomationCatalogError(400, "Case flow.yaml 不是有效 UTF-8 文件") from error

            assets_directory = flow_file.with_suffix(".assets")
            screenshot_names: list[str] = []
            screenshot_digests: list[str] = []
            screenshot_total = 0
            if assets_directory.is_dir():
                for asset in sorted(assets_directory.rglob("*"), key=lambda item: item.as_posix()):
                    if not asset.is_file() or asset.suffix.lower() not in {".png", ".jpg", ".jpeg", ".webp"}:
                        continue
                    if len(screenshot_names) >= MAX_SCREENSHOTS:
                        raise AutomationCatalogError(400, "Case 截图数量超过限制")
                    relative_asset = _sab_screenshot_path(asset.name)
                    if relative_asset in screenshot_names:
                        raise AutomationCatalogError(400, f"Case 包含重复截图文件名：{relative_asset}")
                    target = screenshot_root / relative_asset
                    target.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copyfile(asset, target)
                    screenshot_total += target.stat().st_size
                    if target.stat().st_size > MAX_SCREENSHOT_BYTES:
                        raise AutomationCatalogError(413, "截图大小超过限制")
                    if screenshot_total > MAX_CASE_SCREENSHOTS_BYTES:
                        raise AutomationCatalogError(413, "Case 截图总大小超过限制")
                    screenshot_names.append(relative_asset)
                    screenshot_digests.append(hashlib.sha256(target.read_bytes()).hexdigest())

            manifest = {
                "caseID": case_id,
                "name": name,
                "description": description.strip(),
                "tags": normalized_tags,
                # Maestro stores the target application in the flow frontmatter.
                # Keep it in the catalog manifest so the detail page matches the workspace.
                "targetPackage": next(
                    (
                        match.group(1).strip().strip('"\'')
                        for match in re.finditer(
                            r"^appId:\s*([^#\n]+)", flow.decode("utf-8"), re.MULTILINE
                        )
                    ),
                    "",
                ),
                "validation": {"status": "passed"},
            }
            package_root = temp_root / "package"
            package_root.mkdir(parents=True, exist_ok=True)
            (package_root / "flow.yaml").write_bytes(flow)
            (package_root / "manifest.json").write_text(
                json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
            )
            if screenshot_root.is_dir():
                package_screenshots = package_root / "screenshots"
                shutil.copytree(screenshot_root, package_screenshots)
            with zipfile.ZipFile(temp_package, "w", zipfile.ZIP_DEFLATED) as archive:
                archive.write(package_root / "flow.yaml", "flow.yaml")
                archive.write(package_root / "manifest.json", "manifest.json")
                # Keep the original workspace tree as well as the catalog's
                # canonical flow.yaml. Child flows and non-image assets are
                # needed when a downloaded Case is later executed by Maestro.
                for workspace_file in sorted(workspace_root.rglob("*"), key=lambda item: item.as_posix()):
                    if not workspace_file.is_file():
                        continue
                    relative = workspace_file.relative_to(workspace_root).as_posix()
                    if relative in {"flow.yaml", "manifest.json"}:
                        continue
                    archive.write(workspace_file, relative)
            if temp_package.stat().st_size > MAX_CASE_PACKAGE_BYTES:
                raise AutomationCatalogError(413, "Case 包大小超过限制")
            package_sha256 = hashlib.sha256(temp_package.read_bytes()).hexdigest()
            return await asyncio.to_thread(
                self._finalize_case,
                manifest,
                case_id,
                name,
                temp_package,
                screenshot_root,
                screenshot_names,
                screenshot_digests,
                package_sha256,
                account_id,
                uploaded_by,
            )
        finally:
            self._clean_temp(temp_root)

