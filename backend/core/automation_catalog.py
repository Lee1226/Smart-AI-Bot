    def download_path(
        self, kind: CatalogKind, resource_id: str, version: int, account_id: str | None
    ) -> Path:
        validate_resource_id(resource_id)
        with self._locked():
            found = self._find_record(self._load_index(), kind, resource_id, account_id)
            if not found:
                raise AutomationCatalogError(404, "资源不存在")
            _, record = found
            selected = next(
                (item for item in record.get("versions", []) if item.get("version") == version), None
            )
            if not selected:
                raise AutomationCatalogError(404, "版本不存在")
            source = self._record_path(selected)
            if not source.is_file():
                raise AutomationCatalogError(404, "资源文件不存在")
            return source

