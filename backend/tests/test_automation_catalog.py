@pytest.mark.asyncio
async def test_plan_semantically_deduplicates_content_and_versions_increment_for_changes(tmp_path: Path):
    catalog = AutomationCatalog(tmp_path / "catalog")
    plan_id = "plan-semantic"
    dependencies = [{"caseID": "case-a", "version": 1, "sha256": "A" * 64}]
    manifest = {
        "planID": plan_id,
        "name": "语义去重计划",
        "description": "保持不变",
        "dependencies": dependencies,
        "changeNote": "首次上传",
        "validation": {"status": "passed", "checkedAt": "first"},
    }
    plan_yaml = "cases:\n  - case-a\n"

    await catalog.publish_plan(
        json.dumps(manifest, ensure_ascii=False),
        _upload(
            "plan-semantic.sabplan",
            _plan_package(
                plan_id,
                manifest["name"],
                {"dependencies": dependencies, "changeNote": "package note"},
                plan_yaml,
            ),
        ),
        None,
    )

    duplicate_dependencies = [{"caseID": "case-a", "version": 1, "sha256": "a" * 64}]
    duplicate_manifest = {
        **manifest,
        "dependencies": duplicate_dependencies,
        "changeNote": "修订说明",
        "validation": {"status": "passed", "checkedAt": "second"},
    }
    with pytest.raises(AutomationCatalogError) as duplicate:
        await catalog.publish_plan(
            json.dumps(duplicate_manifest, ensure_ascii=False),
            _upload(
                "plan-semantic.sabplan",
                _plan_package(
                    plan_id,
                    manifest["name"],
                    {"dependencies": duplicate_dependencies, "changeNote": "another package note"},
                    plan_yaml,
                ),
            ),
            None,
        )
    assert duplicate.value.status_code == 409

    changed_yaml = "cases:\n  - case-a\n  - case-b\n"
    changed = await catalog.publish_plan(
        json.dumps({**manifest, "changeNote": "内容版本 2"}, ensure_ascii=False),
        _upload(
            "plan-semantic.sabplan",
            _plan_package(plan_id, manifest["name"], {"dependencies": dependencies}, changed_yaml),
        ),
        None,
    )
    assert changed["version"] == 2

    changed_dependencies = [{"caseID": "case-b", "version": 1, "sha256": "B" * 64}]
    changed_dependencies_result = await catalog.publish_plan(
        json.dumps({**manifest, "dependencies": changed_dependencies}, ensure_ascii=False),
        _upload(
            "plan-semantic.sabplan",
            _plan_package(
                plan_id,
                manifest["name"],
                {"dependencies": changed_dependencies},
                plan_yaml,
            ),
        ),
        None,
    )
    assert changed_dependencies_result["version"] == 3

    detail = catalog.get_resource("plans", plan_id, None)
    assert [version["version"] for version in detail["versions"]] == [1, 2, 3]
    assert len({version["content_sha256"] for version in detail["versions"]}) == 3


