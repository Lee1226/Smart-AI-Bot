def _package(entries: dict[str, bytes]) -> bytes:
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, content in entries.items():
            archive.writestr(name, content)
    return output.getvalue()


def _case_package(case_id: str, name: str, flow: str) -> bytes:
    manifest = json.dumps({"caseID": case_id, "name": name}, ensure_ascii=False).encode()
    return _package({"manifest.json": manifest, "flow.yaml": flow.encode()})


def _plan_package(plan_id: str, name: str, plan_manifest: dict, plan_yaml: str = "cases: []\n") -> bytes:
    return _package({
        "manifest.json": json.dumps({"planID": plan_id, "name": name, **plan_manifest}).encode(),
        "plan.yaml": plan_yaml.encode(),
    })


def _assert_public_payload(value):
    if isinstance(value, dict):
        assert "file_name" not in value
        assert "account_id" not in value
        for item in value.values():
            _assert_public_payload(item)
    elif isinstance(value, list):
        for item in value:
            _assert_public_payload(item)


@pytest.mark.asyncio
async def test_case_preserves_package_extracts_steps_and_rejects_duplicate(tmp_path: Path):
    catalog = AutomationCatalog(tmp_path / "catalog")
    flow = """# sab-recorded-step: token
# sab-before-screenshot: assets/before.png
# sab-result-screenshot: assets/result.png
- tapOn:
    id: \"button\"
# sab-fixed-wait-ms: 1500
# sab-visual-popup-guard: {\"title\": \"确认\"}
# sab-recorded-step: token-2
- assertVisible:
    text: \"完成\"
"""
    package = _case_package("case-1", "演示 Case", flow)
    before = b"before"
    result = b"result"
    manifest = json.dumps({"caseID": "case-1", "name": "演示 Case"})

    created = await catalog.publish_case(
        manifest,
        _upload("case-1.sabcase", package),
        [_upload("before.png", before), _upload("result.png", result)],
        None,
    )
    _assert_public_payload(created)
    assert created["version"] == 1
    detail = catalog.get_resource("cases", "case-1", None)
    _assert_public_payload(detail)
    version = detail["versions"][0]
    assert version["flow_yaml"] == flow
    assert [step.get("action_name") for step in version["steps"] if step["kind"] == "action"] == [
        "tapOn", "assertVisible"
    ]
    assert {step["kind"] for step in version["steps"]} == {"action", "wait", "guard"}
    assert catalog.download_path("cases", "case-1", 1, None).read_bytes() == package
    assert catalog.screenshot_path("case-1", 1, "flow.assets/before.png", None).read_bytes() == before
    _assert_public_payload(catalog.list_resources("cases", "", None))

    with pytest.raises(AutomationCatalogError) as duplicate:
        await catalog.publish_case(
            manifest,
            _upload("case-1.sabcase", package),
            [_upload("before.png", before), _upload("result.png", result)],
            None,
        )
    assert duplicate.value.status_code == 409


