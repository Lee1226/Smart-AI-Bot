@router.get("/cases/{case_id}/versions/{version}/download")
async def download_case(request: Request, case_id: str, version: int):
    try:
        source, filename = await run_in_threadpool(
            catalog.download_snapshot, "cases", case_id, version, _account_id(request)
        )
        return FileResponse(
            source,
            media_type="application/octet-stream",
            filename=filename,
            background=BackgroundTask(_remove_download, str(source)),
        )
    except AutomationCatalogError as error:
        _raise_catalog_error(error)


