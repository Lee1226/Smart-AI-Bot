from core.automation_catalog import AutomationCatalog, AutomationCatalogError, CatalogKind
from db.database import AsyncSessionLocal
from db.models import User


router = APIRouter(prefix="/api/automation", tags=["automation"])
catalog = AutomationCatalog()


def _account_id(request: Request) -> str | None:
    return getattr(request.state, "account_id", None)


async def _uploaded_by(request: Request) -> str:
    """Return a human-readable uploader without treating an API key as a user."""
    user_id = getattr(request.state, "user_id", None) or getattr(request.state, "api_key_created_by", None)
    if user_id:
        async with AsyncSessionLocal() as db:
            user = await db.get(User, user_id)
            if user and user.account_id == _account_id(request):
                return user.name.strip() or user.email
    api_key_name = (getattr(request.state, "api_key_name", None) or "").strip()
    return f"API Key · {api_key_name}" if api_key_name else "未知上传人"


def _raise_catalog_error(error: AutomationCatalogError) -> None:
    raise HTTPException(status_code=error.status_code, detail=error.detail) from error


def _remove_download(path: str) -> None:
    Path(path).unlink(missing_ok=True)


